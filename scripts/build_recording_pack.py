_SIDECAR = {
    "call_id": "c00",
    "pair_id": "AB",
    "turn_id": 1,
    "speaker_role": "AGT|CUS",
    "speaker_id": "S1",
    "take_kept": 1,
    "script_path": "data/scripts/c00.json",
    "device_id": "rec-01",
    "room_id": "room-01",
    "recorded_at": "2026-11-08T10:23:45Z",
    "guide_used": True,
    "rehearsal_drill": False,
    "first_take_default": True,
    "qc_passed": False,
    "notes": "",
}


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def _glossary_index(glossary: list[dict]) -> dict[str, dict]:
    index = {}
    for entry in glossary:
        term_id = entry.get("term_id") or entry.get("id")
        if isinstance(term_id, str) and term_id:
            index[term_id] = entry
    return index


def _reference_text(script: Mapping[str, Any]) -> str:
    return " ".join(
        str(turn.get("text", "")).strip()
        for turn in script.get("turns", [])
        if str(turn.get("text", "")).strip()
    )


def _term_rows(script: Mapping[str, Any], glossary: Mapping[str, dict]) -> list[dict]:
    seen: list[str] = []
    for turn in script.get("turns", []):
        for term_id in turn.get("glossary_terms", []) or []:
            if term_id not in seen:
                seen.append(term_id)
    rows = []
    for term_id in seen:
        entry = glossary.get(term_id)
        rows.append(
            {
                "term_id": term_id,
                "written": (entry or {}).get("canonical") or "—",
                "origin": (entry or {}).get("origin") or "—",
                "category": (entry or {}).get("category") or "—",
                "status": "resolved" if entry else "MISSING",
            }
        )
    return rows


def render_call_sheet(call_id: str, script: Mapping[str, Any], glossary: Mapping[str, dict]) -> str:
    lines = [
        f"# Call {call_id}",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Call ID | {call_id} |",
        f"| Call type | {script.get('call_type', '—')} |",
        f"| Mismatched domain | {script.get('mismatched_domain', '—')} |",
        f"| Speakers | {', '.join(script.get('speakers', [])) or '—'} |",
        f"| Turns | {len(script.get('turns', []))} |",
        "",
        "## Dialogue",
        "",
        "Read naturally. Do not spell, list, or hyper-articulate the target terms.",
        "",
        "| Turn | Speaker | Say this |",
        "|---|---|---|",
    ]
    for turn in script.get("turns", []):
        text = str(turn.get("text", "")).replace("|", "\\|")
        lines.append(f"| {turn.get('idx', '')} | {turn.get('speaker', '')} | {text} |")

    terms = _term_rows(script, glossary)
    lines += [
        "",
        "## Target terms (do not read as a list)",
        "",
        "| Term ID | Written form | Origin | Category | Status |",
        "|---|---|---|---|---|",
    ]
    for row in terms:
        lines.append(
            f"| {row['term_id']} | {row['written']} | {row['origin']} | "
            f"{row['category']} | {row['status']} |"
        )
    if any(row["status"] == "MISSING" for row in terms):
        lines += [
            "",
            "> **MISSING** means the term ID is not in the committed glossary. The "
            "dialogue still contains the spoken form; use the customer glossary for "
            "a real study.",
        ]
    lines += [
        "",
        "## Delivery",
        "",
        "- Natural conversational pace; no rehearsal drill; first take is the default.",
        "- Record the whole call in one session, one device, one room.",
        "- Save as `audio/<call>.wav` in this pack; paths stay relative.",
        "- The reference transcript is `refs/<call>.txt`; do not edit it.",
        "",
    ]
    return "\n".join(lines)


def build_pack(
    calls: list[str] | tuple[str, ...] = DEFAULT_CALLS,
    *,
    out_dir: str | Path = "recording",
    glossary_path: str | Path = "data/glossary.json",
    scripts_dir: str | Path = "data/scripts",
    study_id: str = "gnani-bfsi-recording-1",
) -> dict[str, Any]:
    """Generate the complete pack; returns a summary dict."""
    out = Path(out_dir)
    scripts_root = Path(scripts_dir)
    glossary = _glossary_index(_load_json(Path(glossary_path)))

    (out / "scripts").mkdir(parents=True, exist_ok=True)
    (out / "refs").mkdir(parents=True, exist_ok=True)
    (out / "audio").mkdir(parents=True, exist_ok=True)

    manifest_calls = []
    missing: dict[str, list[str]] = {}
    missing_scripts: list[str] = []
    for call_id in calls:
        script_path = scripts_root / f"{call_id}.json"
        if not script_path.is_file():
            missing_scripts.append(call_id)
            continue
        script = _load_json(script_path)
        sheet = render_call_sheet(call_id, script, glossary)
        (out / "scripts" / f"{call_id}.md").write_text(sheet, encoding="utf-8")
        (out / "refs" / f"{call_id}.txt").write_text(
            _reference_text(script), encoding="utf-8"
        )
        unresolved = [
            row["term_id"]
            for row in _term_rows(script, glossary)
            if row["status"] == "MISSING"
        ]
        if unresolved:
            missing[call_id] = unresolved
        manifest_calls.append(
            {
                "call_id": call_id,
                "audio": f"audio/{call_id}.wav",
                "reference": f"refs/{call_id}.txt",
                "call_type": script.get("call_type") or "general",
                "utterances": len(script.get("turns", [])),
                "mismatched_domain": script.get("mismatched_domain"),
                "must_have": [],
                "consent_ref": "consent.md",
                "pii_status": "pending",
            }
        )

    (out / "README.md").write_text(_README, encoding="utf-8")
    (out / "consent.md").write_text(_CONSENT, encoding="utf-8")
    (out / "qc-checklist.md").write_text(_QC, encoding="utf-8")
    (out / "sidecar.template.json").write_text(
        json.dumps(_SIDECAR, indent=2) + "\n", encoding="utf-8"
    )
    manifest = {"study_id": study_id, "calls": manifest_calls}
    (out / "manifest.template.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    return {
        "out_dir": str(out),
        "calls": [call["call_id"] for call in manifest_calls],
        "manifest": manifest,
        "missing_terms": missing,
        "missing_scripts": missing_scripts,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the LexiForge recording pack")
    parser.add_argument(
        "--calls",
        default=",".join(DEFAULT_CALLS),
        help="Comma-separated call ids (default: c00..c19)",
    )
    parser.add_argument("--out", default="recording")
    parser.add_argument("--glossary", default="data/glossary.json")
    parser.add_argument("--scripts-dir", default="data/scripts")
    parser.add_argument("--study-id", default="gnani-bfsi-recording-1")
    args = parser.parse_args(argv)

    calls = [c.strip() for c in args.calls.split(",") if c.strip()]
    summary = build_pack(
        calls,
        out_dir=args.out,
        glossary_path=args.glossary,
        scripts_dir=args.scripts_dir,
        study_id=args.study_id,
    )
    print(f"built {len(summary['calls'])} call sheets in {summary['out_dir']}")
    if summary["missing_scripts"]:
        print(
            "WARNING: skipped calls with no script: "
            + ", ".join(summary["missing_scripts"])
        )
    if summary["missing_terms"]:
        print("unresolved term ids (dialogue still usable):")
        for call_id, ids in summary["missing_terms"].items():
            print(f"  {call_id}: {', '.join(ids)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

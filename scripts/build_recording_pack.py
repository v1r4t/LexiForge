"""Build a printable recording pack from data/scripts/*.json.

Outputs under ``recording/`` by default:

  README.md, consent.md, qc-checklist.md
  scripts/<call>.md        human call sheets
  refs/<call>.txt          reference transcripts for scoring
  manifest.template.json   intake manifest for scripts/run_keyterm_study.py
  sidecar.template.json    per-file metadata template

The pack is generated, not hand-copied, so it stays in sync with the committed
scripts and glossary. Manifest paths are relative to the pack directory and
always use forward slashes, so the pack stays portable (design §5; P12).

A call whose ``data/scripts/<call>.json`` is absent is skipped and reported in
``summary["missing_scripts"]``; the generator never invents dialogue.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping

__all__ = ["DEFAULT_CALLS", "build_pack", "render_call_sheet", "main"]

DEFAULT_CALLS = tuple(f"c{index:02d}" for index in range(20))

_README = """# LexiForge recording pack

Generated by `scripts/build_recording_pack.py`. Do not hand-edit the call
sheets; regenerate them instead. This pack is preparation only: no audio is
included, and no result may be claimed until the calls are recorded, checked
with `record_check.py`, and scored.

## Contents

- `scripts/<call>.md` — call sheet: dialogue, target terms, delivery rules.
- `refs/<call>.txt` — reference transcript, generated from the script.
- `manifest.template.json` — intake manifest; references are pre-filled.
- `sidecar.template.json` — per-file metadata template.
- `consent.md` — per-speaker consent form (sign before the first take).
- `qc-checklist.md` — six QC items plus the retake log.

## Before recording

1. Read `consent.md`; every speaker signs it before the first take.
2. Read `qc-checklist.md` and `docs/consent-and-redaction.md`.
3. One session per call, one device, one room, both speakers present.
4. First take is the default. No rehearsal drill, no hyper-articulation.

## Record

For each call, open `scripts/<call>.md` and record the dialogue as written.
Audio files go to `audio/<call>.wav` (gitignored).

The reference transcript is already written to `refs/<call>.txt`; do not edit it
to match what you heard. It is the ground truth the scorer compares against.

## After recording

1. Fill `manifest.template.json` (rename it to `manifest.json`) with one audio
   file per call. Paths are relative to this directory and use forward slashes.
2. Validate from the repository root:

```bash
python scripts/record_check.py recording/manifest.json
```

3. Dry-run the study from inside the pack directory, then execute:

```bash
cd recording
python ../scripts/run_keyterm_study.py manifest.json --glossary ../data/glossary.json
python ../scripts/run_keyterm_study.py manifest.json --glossary ../data/glossary.json --execute
```

## Completeness

The pack is only as complete as `data/scripts/`. If a call has no script, the
build prints it under "skipped calls" and the pack has fewer than 20 sheets.
Regenerate after the missing scripts land; never add a sheet by hand.

## Data note

The committed glossary has 1,000 terms. Some script target IDs (for example
`R1171`) are not present in it; those rows are marked **MISSING** in the
pronunciation sheet. The dialogue still contains the spoken terms. For a real
study, pass the customer glossary instead.
"""


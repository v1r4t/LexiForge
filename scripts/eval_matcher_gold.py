#!/usr/bin/env python3
"""Score the hand-labelled matcher gold set (design section 5, task P05).

Labels live in ``tests/gold/matcher_gold.jsonl`` and are written by hand from
the frozen :mod:`lexiforge.canon` rules; they are never generated by
``find_spans``. This script only measures the matcher against them:
precision/recall/F1 at span level, with the CLI exiting 1 when any of the
three falls below 0.98 (one wrong span in the set must fail the gate).

Cases may carry a ``stratum`` tag (``acronym``, ``variant``,
``transliteration`` or ``negative``) so the same gate can be reported per
stratum; untagged cases are reported as ``core``.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, List, Optional

from lexiforge.score.match import find_spans, load_glossary

REPO_ROOT = Path(__file__).resolve().parents[1]
GOLD_PATH = REPO_ROOT / "tests" / "gold" / "matcher_gold.jsonl"
THRESHOLD = 0.98
STRATA = ("acronym", "variant", "transliteration", "negative")
CORE_STRATUM = "core"
_METRICS = ("precision", "recall", "f1")


def _load_cases(path) -> list[dict]:
    cases: list[dict] = []
    for lineno, line in enumerate(
        Path(path).read_text(encoding="utf-8").splitlines(), start=1
    ):
        if not line.strip():
            continue
        try:
            cases.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path}:{lineno}: invalid JSON: {exc}") from exc
    return cases


def _case_glossary(case: dict, fallback: Optional[list[dict]]) -> list[dict]:
    glossary = case.get("glossary")
    if glossary is None:
        if fallback is None:
            raise ValueError(
                f"case {case.get('id')!r} has no glossary and no fallback was given"
            )
        return fallback
    return glossary


def _case_stratum(case: dict) -> str:
    stratum = case.get("stratum", CORE_STRATUM)
    if stratum not in (CORE_STRATUM, *STRATA):
        raise ValueError(
            f"case {case.get('id')!r} has unknown stratum {stratum!r}; "
            f"expected one of {list((CORE_STRATUM, *STRATA))}"
        )
    return stratum


def _span_keys(spans) -> set[tuple[str, int, int]]:
    return {(str(span["term_id"]), int(span["start"]), int(span["end"])) for span in spans}


def _score_case(case: dict, fallback: Optional[list[dict]]):
    """Return ``(true_positives, false_positives, false_negatives)`` for a case."""
    _case_stratum(case)  # reject typo'd stratum tags on every path
    glossary = _case_glossary(case, fallback)
    predicted = _span_keys(find_spans(case["text"], glossary))
    expected = _span_keys(case["expected_spans"])
    return predicted & expected, predicted - expected, expected - predicted


def _metrics(counts: dict[str, int]) -> dict[str, Any]:
    tp, fp, fn = counts["tp"], counts["fp"], counts["fn"]
    precision = tp / (tp + fp) if tp + fp else 1.0
    recall = tp / (tp + fn) if tp + fn else 1.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": tp,
        "fp": fp,
        "fn": fn,
    }


def evaluate(path=GOLD_PATH, glossary_path=None) -> dict[str, Any]:
    """Return ``precision``, ``recall``, ``f1``, ``tp``, ``fp``, ``fn``.

    ``glossary_path`` is an optional fallback glossary used only by cases
    that do not carry an inline ``glossary``.
    """
    fallback = load_glossary(glossary_path) if glossary_path is not None else None
    counts = {"tp": 0, "fp": 0, "fn": 0}
    for case in _load_cases(path):
        tp, fp, fn = _score_case(case, fallback)
        counts["tp"] += len(tp)
        counts["fp"] += len(fp)
        counts["fn"] += len(fn)
    return _metrics(counts)


def evaluate_by_stratum(path=GOLD_PATH, glossary_path=None) -> dict[str, dict]:
    """Return the same metrics keyed by stratum, plus a case count per stratum.

    Untagged cases are reported under ``core``; every other case must carry
    one of :data:`STRATA` or a ``ValueError`` is raised.
    """
    fallback = load_glossary(glossary_path) if glossary_path is not None else None
    buckets = {
        name: {"tp": 0, "fp": 0, "fn": 0, "cases": 0}
        for name in (CORE_STRATUM, *STRATA)
    }
    for case in _load_cases(path):
        bucket = buckets[_case_stratum(case)]
        tp, fp, fn = _score_case(case, fallback)
        bucket["tp"] += len(tp)
        bucket["fp"] += len(fp)
        bucket["fn"] += len(fn)
        bucket["cases"] += 1
    return {
        name: _metrics(bucket) | {"cases": bucket["cases"]}
        for name, bucket in buckets.items()
    }


def _passes(metrics: dict[str, Any]) -> bool:
    return all(metrics[metric] >= THRESHOLD for metric in _METRICS)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", nargs="?", default=str(GOLD_PATH), help="gold JSONL file")
    parser.add_argument(
        "--glossary",
        default=None,
        help="fallback glossary JSON for cases without an inline glossary",
    )
    parser.add_argument(
        "--by-stratum",
        action="store_true",
        help="report metrics per stratum and gate each stratum at the threshold",
    )
    args = parser.parse_args(argv)
    if args.by_stratum:
        by_stratum = evaluate_by_stratum(args.path, args.glossary)
        print(json.dumps(by_stratum, indent=2, sort_keys=True))
        passed = _passes(evaluate(args.path, args.glossary)) and all(
            _passes(metrics) for metrics in by_stratum.values()
        )
        return 0 if passed else 1
    result = evaluate(args.path, args.glossary)
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if _passes(result) else 1


if __name__ == "__main__":
    raise SystemExit(main())

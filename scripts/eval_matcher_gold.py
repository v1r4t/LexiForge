#!/usr/bin/env python3
"""Score the hand-labelled matcher gold set.

Labels live in ``tests/gold/matcher_gold.jsonl`` and are written by hand from
the frozen :mod:`lexiforge.canon` rules; they are never generated by
``find_spans``. This script only measures the matcher against them:
precision/recall/F1 at span level, with the CLI exiting 1 when any of the
three falls below 0.98 (one wrong span in a 30-case set must fail the gate).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, List, Optional

from lexiforge.score.match import find_spans, load_glossary

REPO_ROOT = Path(__file__).resolve().parents[1]
GOLD_PATH = REPO_ROOT / "tests" / "gold" / "matcher_gold.jsonl"
THRESHOLD = 0.98


def _load_cases(path) -> list[dict]:
    cases: list[dict] = []
    for lineno, line in enumerate(
        Path(path).read_text(encoding="utf-8").splitlines(), start=1
    ):
        if not line.strip():
            continue
        try:
            cases.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path}:{lineno}: invalid JSON: {exc}") from exc
    return cases


def _case_glossary(case: dict, fallback: Optional[list[dict]]) -> list[dict]:
    glossary = case.get("glossary")
    if glossary is None:
        if fallback is None:
            raise ValueError(
                f"case {case.get('id')!r} has no glossary and no fallback was given"
            )
        return fallback
    return glossary


def _span_keys(spans) -> set[tuple[str, int, int]]:
    return {(str(span["term_id"]), int(span["start"]), int(span["end"])) for span in spans}


def evaluate(path=GOLD_PATH, glossary_path=None) -> dict[str, Any]:
    """Return ``precision``, ``recall``, ``f1``, ``tp``, ``fp``, ``fn``.

    ``glossary_path`` is an optional fallback glossary used only by cases
    that do not carry an inline ``glossary``.
    """
    fallback = load_glossary(glossary_path) if glossary_path is not None else None
    tp = fp = fn = 0
    for case in _load_cases(path):
        glossary = _case_glossary(case, fallback)
        predicted = _span_keys(find_spans(case["text"], glossary))
        expected = _span_keys(case["expected_spans"])
        tp += len(predicted & expected)
        fp += len(predicted - expected)
        fn += len(expected - predicted)
    precision = tp / (tp + fp) if tp + fp else 1.0
    recall = tp / (tp + fn) if tp + fn else 1.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": tp,
        "fp": fp,
        "fn": fn,
    }


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", nargs="?", default=str(GOLD_PATH), help="gold JSONL file")
    parser.add_argument(
        "--glossary",
        default=None,
        help="fallback glossary JSON for cases without an inline glossary",
    )
    args = parser.parse_args(argv)
    result = evaluate(args.path, args.glossary)
    print(json.dumps(result, indent=2, sort_keys=True))
    passed = all(result[metric] >= THRESHOLD for metric in ("precision", "recall", "f1"))
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
